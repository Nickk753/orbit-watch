"""Data quality checks on data/model/*.csv: row counts, date coverage, nulls, duplicate keys, orphan FKs.
Writes docs/data-checks.md. Run: python3 pipeline/checks.py"""
import csv, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
M = os.path.join(ROOT, "data", "model")
T = {n: list(csv.DictReader(open(os.path.join(M, n + ".csv")))) for n in
     ["dim_satellite", "dim_object", "dim_date", "dim_risk_tier", "fact_conjunction", "fact_maneuver"]}
PK = {"dim_satellite": "satellite_id", "dim_object": "object_id", "dim_date": "date_key",
      "dim_risk_tier": "risk_tier", "fact_conjunction": "conjunction_id", "fact_maneuver": "maneuver_id"}
FK = [("fact_conjunction", "satellite_id", "dim_satellite"), ("fact_conjunction", "object_id", "dim_object"),
      ("fact_conjunction", "tca_date", "dim_date"), ("fact_conjunction", "risk_tier", "dim_risk_tier"),
      ("fact_maneuver", "satellite_id", "dim_satellite"), ("fact_maneuver", "maneuver_date", "dim_date"),
      ("fact_maneuver", "conjunction_id", "fact_conjunction")]
OPTIONAL = {("fact_maneuver", "conjunction_id")}  # empty = station keeping (no triggering event), by design

lines = ["# Data checks", "", "Generated by `pipeline/checks.py`. Every check must read PASS before the model is used.", "",
         "## Row counts and coverage", "", "| Table | Rows | Columns | Date coverage |", "| --- | --- | --- | --- |"]
cov = {"fact_conjunction": "tca_date", "fact_maneuver": "maneuver_date", "dim_date": "date_key"}
for n, rows in T.items():
    c = cov.get(n)
    rng = f"{min(r[c] for r in rows)} to {max(r[c] for r in rows)}" if c else "n/a"
    lines.append(f"| {n} | {len(rows):,} | {len(rows[0])} | {rng} |")

lines += ["", "## Checks", "", "| Check | Table.column | Result | Detail |", "| --- | --- | --- | --- |"]
ok = True
for n, rows in T.items():
    keys = [r[PK[n]] for r in rows]
    dup = len(keys) - len(set(keys))
    ok &= dup == 0
    lines.append(f"| Duplicate primary keys | {n}.{PK[n]} | {'PASS' if dup == 0 else 'FAIL'} | {dup} duplicates |")
for n, rows in T.items():
    for col in rows[0]:
        miss = sum(1 for r in rows if r[col] == "")
        if (n, col) in OPTIONAL:
            lines.append(f"| Missing values (allowed) | {n}.{col} | PASS | {miss} empty = station-keeping burns, no trigger event |")
        elif miss:
            ok = False
            lines.append(f"| Missing values | {n}.{col} | FAIL | {miss} empty |")
lines.append("| Missing values | all other columns | PASS | 0 empty |")
for f, col, d in FK:
    dk = {r[PK[d]] for r in T[d]}
    vals = [r[col] for r in T[f] if r[col] != ""]
    orph = sum(1 for v in vals if v not in dk)
    ok &= orph == 0
    lines.append(f"| Orphan foreign keys | {f}.{col} -> {d} | {'PASS' if orph == 0 else 'FAIL'} | {orph} of {len(vals):,} unmatched |")
links = [r["conjunction_id"] for r in T["fact_maneuver"] if r["conjunction_id"]]
d1 = len(links) - len(set(links))
ok &= d1 == 0
lines.append(f"| At most one maneuver per conjunction | fact_maneuver.conjunction_id | {'PASS' if d1 == 0 else 'FAIL'} | {d1} conjunctions with 2+ maneuvers |")
bad = sum(1 for r in T["fact_conjunction"] if not (0 <= float(r["pc"]) <= 1) or float(r["miss_distance_m"]) < 0)
ok &= bad == 0
lines.append(f"| Value ranges (0 <= Pc <= 1, miss >= 0) | fact_conjunction | {'PASS' if bad == 0 else 'FAIL'} | {bad} out of range |")
lines += ["", f"**Overall: {'ALL PASS' if ok else 'FAILURES FOUND'}**"]
open(os.path.join(ROOT, "docs", "data-checks.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
