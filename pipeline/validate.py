"""Exercise 4: reconcile KPIs computed directly from the source CSVs with the same KPIs
computed through the Supabase model (v_conjunction + kpi_summary), same period and filters.
Also checks row counts before/after the joins. Writes docs/validation.md.
Needs SUPABASE_URL and SUPABASE_KEY (publishable, read-only)."""
import csv, json, os, urllib.request
from datetime import date, timedelta
from decimal import Decimal, ROUND_HALF_UP


def rnd(x, n):
    """Round half away from zero, like Postgres numeric round(). Python round() rounds 15.725 -> 15.72."""
    return float(Decimal(str(x)).quantize(Decimal(1).scaleb(-n), rounding=ROUND_HALF_UP))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL, KEY = os.environ["SUPABASE_URL"].rstrip("/"), os.environ["SUPABASE_KEY"]
H = {"apikey": KEY, "Authorization": f"Bearer {KEY}", "Content-Type": "application/json"}
M = lambda n: list(csv.DictReader(open(os.path.join(ROOT, "data", "model", n + ".csv"))))
sats, objs, conj, man = M("dim_satellite"), M("dim_object"), M("fact_conjunction"), M("fact_maneuver")
otype = {o["object_id"]: o["object_type"] for o in objs}
plane = {s["satellite_id"]: int(s["plane"]) for s in sats}


def rest_count(path):
    req = urllib.request.Request(f"{URL}/rest/v1/{path}", headers={**H, "Prefer": "count=exact", "Range": "0-0"})
    with urllib.request.urlopen(req) as r:
        return int(r.headers["Content-Range"].split("/")[1])


def rpc(args):
    req = urllib.request.Request(f"{URL}/rest/v1/rpc/kpi_summary", data=json.dumps(args).encode(), headers=H, method="POST")
    return json.loads(urllib.request.urlopen(req).read())[0]


def source(start, end, p=None, t=None):
    S = [s for s in sats if p is None or int(s["plane"]) == p]
    ids = {s["satellite_id"] for s in S}
    days = (end - start).days + 1
    c = [r for r in conj if r["satellite_id"] in ids and start.isoformat() <= r["tca_date"] <= end.isoformat()
         and (t is None or otype[r["object_id"]] == t)]
    m = [r for r in man if r["satellite_id"] in ids and r["maneuver_type"] == "Collision avoidance"
         and start.isoformat() <= r["maneuver_date"] <= end.isoformat()]
    hi = sum(1 for r in c if r["risk_tier"] == "High")
    return {
        "satellites_in_scope": len(S), "conjunctions": len(c), "high_risk": hi,
        "conjunctions_per_sat_30d": rnd(len(c) * 30 / (len(S) * days), 2) if S else None,
        "high_risk_share_pct": rnd(100 * hi / len(c), 2) if c else None,
        "avoidance_maneuvers": len(m), "avoidance_maneuvers_per_sat": rnd(len(m) / len(S), 3) if S else None,
        "expected_collisions": round(sum(float(r["pc"]) for r in c), 6),
        "avoidance_fuel_kg": round(sum(float(r["fuel_kg"]) for r in m), 3),
    }


AS_OF = date(2026, 11, 10)
cases = [
    ("Last 30 days, whole fleet", AS_OF - timedelta(days=30), AS_OF - timedelta(days=1), None, None),
    ("Previous 30 days, whole fleet", AS_OF - timedelta(days=60), AS_OF - timedelta(days=31), None, None),
    ("Last 30 days, plane 3, debris only", AS_OF - timedelta(days=30), AS_OF - timedelta(days=1), 3, "Debris"),
    ("Next 30 days (forecast), whole fleet", AS_OF, AS_OF + timedelta(days=29), None, None),
]
lines = ["# Validation: source vs model", "",
         "Source = Python over the generated CSVs (`data/model`). Model = Supabase `kpi_summary()` over `v_conjunction` "
         "and `fact_maneuver`, called through the public REST API with the read-only key. Generated by `pipeline/validate.py`.", "",
         "## 1. Join row counts", "", "| Check | Source CSV | Supabase | Difference |", "| --- | --- | --- | --- |"]
ok = True
for label, n, path in [("fact_conjunction rows", len(conj), "fact_conjunction?select=conjunction_id"),
                       ("v_conjunction rows (after 4 joins)", len(conj), "v_conjunction?select=conjunction_id"),
                       ("fact_maneuver rows", len(man), "fact_maneuver?select=maneuver_id"),
                       ("dim_satellite rows", len(sats), "dim_satellite?select=satellite_id"),
                       ("dim_object rows", len(objs), "dim_object?select=object_id")]:
    db = rest_count(path)
    ok &= db == n
    lines.append(f"| {label} | {n:,} | {db:,} | {db - n} |")

lines += ["", "## 2. KPI reconciliation", ""]
for name, s, e, p, t in cases:
    src = source(s, e, p, t)
    mod = rpc({"p_start": s.isoformat(), "p_end": e.isoformat(), "p_plane": p, "p_object_type": t})
    lines += [f"**{name}** ({s} to {e}{', plane ' + str(p) if p else ''}{', ' + t if t else ''})", "",
              "| KPI / component | Source | Model | Difference |", "| --- | --- | --- | --- |"]
    for k, v in src.items():
        mv = mod[k]
        diff = None if v is None or mv is None else round(float(mv) - float(v), 6)
        ok &= (v is None and mv is None) or diff == 0
        lines.append(f"| {k} | {v} | {mv} | {diff} |")
    lines.append("")
lines += ["", "Note: the first run showed differences of 0.01 and 0.001 on two ratio KPIs. Numerators and denominators matched exactly; "
          "the cause was rounding (Python rounds 15.725 to 15.72, Postgres to 15.73). The source side now rounds half away from zero, like the model. "
          "The KPI definition did not change.", ""]
lines.append(f"**Overall: {'ALL MATCH (difference 0)' if ok else 'MISMATCH FOUND'}**")
open(os.path.join(ROOT, "docs", "validation.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
